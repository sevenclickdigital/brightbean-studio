from providers.meta_feed_extras import FEELINGS

# The feeling labels, marked here rather than in providers/: that package is
# deliberately Django-free, so it cannot call gettext itself.
#
# A dict rather than a list comprehension over FEELINGS, because
# makemessages reads source text — a _(variable) extracts nothing.
_FEELING_LABELS = {
    "happy": gettext_noop("happy"),
    "blessed": gettext_noop("blessed"),
    "loved": gettext_noop("loved"),
    "excited": gettext_noop("excited"),
    "grateful": gettext_noop("grateful"),
    "thankful": gettext_noop("thankful"),
    "accomplished": gettext_noop("accomplished"),
    "amazed": gettext_noop("amazed"),
    "inspired": gettext_noop("inspired"),
    "proud": gettext_noop("proud"),
    "confident": gettext_noop("confident"),
    "peaceful": gettext_noop("peaceful"),
    "content": gettext_noop("content"),
    "joyful": gettext_noop("joyful"),
}


def facebook_feeling_choices() -> list[dict]:
    """The feeling picker's options, translated for the active language."""
    return [
        {"id": feeling_id, "label": _(_FEELING_LABELS.get(label, label))}
        for feeling_id, label in FEELINGS
    ]


