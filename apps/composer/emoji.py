"""Emoji catalogue for the composer's caption picker.

Generated from the Unicode database rather than typed by hand, so the
search keywords are the official character names and nothing is a
transcription error. The ranges are curated: Unicode defines far more
emoji than a caption picker needs, and a wall of rarely-used glyphs makes
the common ones harder to find.

Pure text, so this works for every platform — unlike the Facebook place
and feeling pickers, nothing here touches an API.
"""

from __future__ import annotations

